type FlatPackage = { category: string; pack: Package }

function flatten(root: Package): FlatPackage[] {
  const out: FlatPackage[] = []
  const walk = (pack: Package, prefix: string | null) => {
    const category = prefix === null
      ? null
      : prefix
      ? `${prefix}.${pack.category}`
      : pack.category
    if (category !== null) out.push({ category, pack })
    for (const sub of pack.subpackages) walk(sub, category ?? "")
  }
  walk(root, null)
  return out
}

function categoryDir(category: string): string {
  return category.split(".").map((s) => s.toLowerCase()).join("/")
}

function categoryPkgName(category: string): string {
  const parts = category.split(".")
  return ident(parts[parts.length - 1].toLowerCase(), { category })
}

function categoryImport(category: string): string {
  return `${ROOT_IMPORT}/${categoryDir(category)}`
}

function normalizeCategory(category: string | null): string {
  return category ?? "platform"
}

function clientTypeName(category: string): string {
  return category.split(".").map(pascal).join("") + "Client"
}

