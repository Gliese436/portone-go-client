const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/

function ident(name: string, context: unknown): string {
  if (!IDENT.test(name)) {
    throw new Error(`invalid Go identifier: ${name}`, { cause: context })
  }
  return name
}

function pascal(name: string): string {
  return ident(toPascalCase(name), { name })
}

function lowerFirst(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1)
}

function goString(value: string): string {
  return JSON.stringify(value)
}

function tag(name: string, omitempty: boolean): string {
  return "`json:" + goString(omitempty ? `${name},omitempty` : name) + "`"
}

function annotate(text: string, def: { format?: string | null }): string {
  const format = "format" in def ? def.format : null
  switch (format) {
    case undefined:
    case null:
    case "double":
    case "float":
    case "binary":
      return text
    case "int32":
    case "int64":
      return [text.trimEnd(), `(${format})`].filter(Boolean).join("\n")
    case "date":
      return [text.trimEnd(), "(yyyy-MM-dd)"].filter(Boolean).join("\n")
    case "date-time":
      return [text.trimEnd(), "(RFC 3339 date-time)"].filter(Boolean).join(
        "\n",
      )
    default:
      throw new Error(`unrecognized format ${format}`, { cause: def })
  }
}

/** title 과 description 을 합칩니다. description 이 title 로 시작하면 중복을 제거합니다. */
function mergeDoc(title: string | null, description: string | null): string {
  const t = (title ?? "").trim()
  const d = (description ?? "").trim()
  if (!t) return d
  if (!d) return t
  if (d === t || d.startsWith(t + "\n") || d.startsWith(t)) return d
  return `${t}\n\n${d}`
}

class GoFile {
  readonly imports = new Map<string, string>()
  readonly lines: string[] = []
  constructor(
    readonly pkgName: string,
    /** 이 파일이 속한 카테고리. 루트 패키지면 null */
    readonly category: string | null,
  ) {}

  importPath(importPath: string, preferred?: string): string {
    const existing = this.imports.get(importPath)
    if (existing) return existing
    const base = preferred ?? importPath.slice(importPath.lastIndexOf("/") + 1)
    let alias = base
    const used = new Set(this.imports.values())
    if (used.has(alias)) {
      alias = importPath.slice(ROOT_IMPORT.length + 1).replaceAll("/", "")
    }
    if (used.has(alias)) {
      throw new Error(`import alias collision: ${importPath}`)
    }
    this.imports.set(importPath, alias)
    return alias
  }

  line(text = "") {
    this.lines.push(text)
  }

  doc(indent: string, name: string, text: string | null) {
    const trimmed = (text ?? "").trim()
    if (!trimmed) return
    const ls = trimmed.split("\n").map((l) => l.trimEnd())
    this.line(`${indent}// ${name} ${ls[0]}`.trimEnd())
    for (const l of ls.slice(1)) {
      this.line(l ? `${indent}// ${l}` : `${indent}//`)
    }
  }

  render(): string {
    const out: string[] = [HEADER, "", `package ${this.pkgName}`, ""]
    if (this.imports.size > 0) {
      const std: string[] = []
      const local: string[] = []
      for (const [p, alias] of [...this.imports.entries()].sort()) {
        const base = p.slice(p.lastIndexOf("/") + 1)
        const spec = alias === base ? goString(p) : `${alias} ${goString(p)}`
        if (p.includes(".")) local.push(spec)
        else std.push(spec)
      }
      out.push("import (")
      for (const s of std) out.push(`\t${s}`)
      if (std.length && local.length) out.push("")
      for (const s of local) out.push(`\t${s}`)
      out.push(")", "")
    }
    return out.concat(this.lines).join("\n").replace(/\n{3,}/g, "\n\n") +
      "\n"
  }
}

/** 패키지 내 식별자 충돌 검사 */
class Scope {
  private readonly names = new Map<string, string>()
  constructor(readonly label: string) {}
  add(name: string, owner: string) {
    const prev = this.names.get(name)
    if (prev !== undefined) {
      throw new Error(
        `identifier collision in ${this.label}: ${name} (${prev} vs ${owner})`,
      )
    }
    this.names.set(name, owner)
  }
}

