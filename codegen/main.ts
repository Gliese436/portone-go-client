const root = packageSchema()
const packages = flatten(root)

const entityMap = new Map<string, Definition>()
const categoryMap = new Map<string, string>()
for (const { category, pack } of packages) {
  for (const entity of pack.entities) {
    if (entityMap.has(entity.name)) {
      throw new Error(`duplicated entity ${entity.name}`)
    }
    entityMap.set(entity.name, entity)
    categoryMap.set(entity.name, category)
  }
}

// 하나의 variant 가 서로 다른 판별자 값으로 여러 oneOf 에 속하는지 검사
{
  const seen = new Map<string, string>()
  for (const def of entityMap.values()) {
    if (def.type !== "oneOf") continue
    for (const variant of def.variants) {
      const key = `${variant.name}.${def.property}`
      const prev = seen.get(key)
      if (prev !== undefined && prev !== variant.value) {
        throw new Error(
          `variant ${variant.name} has conflicting discriminator values for ${def.property}: ${prev}, ${variant.value}`,
        )
      }
      seen.set(key, variant.value)
    }
  }
}

function qualify(file: GoFile, name: string): string {
  const category = categoryMap.get(name)
  if (!category) throw new Error(`unknown entity ${name}`)
  if (file.category === category) return name
  const alias = file.importPath(
    categoryImport(category),
    categoryPkgName(category),
  )
  return `${alias}.${name}`
}

/** 엔티티가 Go 에서 nil 이 될 수 있는 타입(map)인지 */
function isNilableEntity(name: string): boolean {
  const def = entityMap.get(name)
  return def?.type === "object" && def.properties.length === 0 &&
    def.additionalProperties !== null
}

type GoType = { type: string; nilable: boolean }

function baseType(file: GoFile, def: Definition): GoType {
  switch (def.type) {
    case "string":
      return { type: "string", nilable: false }
    case "boolean":
      return { type: "bool", nilable: false }
    case "integer":
      return { type: "int64", nilable: false }
    case "number":
      return { type: "float64", nilable: false }
    case "ref":
      return { type: qualify(file, def.value), nilable: isNilableEntity(def.value) }
    case "array": {
      const item = baseType(file, def.item)
      return { type: `[]${item.type}`, nilable: true }
    }
    case "object":
      if (def.properties.length === 0 && def.additionalProperties === null) {
        return { type: "any", nilable: true }
      }
      throw new Error("inline object with properties is not supported", {
        cause: def,
      })
    default:
      throw new Error(`unsupported inline type ${def.type}`, { cause: def })
  }
}

function fieldType(file: GoFile, prop: Property): string {
  const t = baseType(file, prop)
  return !prop.required && !t.nilable ? `*${t.type}` : t.type
}

function fetchBodyProperties(op: Operation): Property[] {
  const body = op.params.body
  if (!body) return []
  if (body.type !== "ref") {
    throw new Error("unsupported body type", { cause: op })
  }
  const actual = entityMap.get(body.value)
  if (!actual || actual.type !== "object") {
    throw new Error("unsupported actual body type", { cause: op })
  }
  return actual.properties
}

