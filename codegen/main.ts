async function removeGenerated(dir: string) {
  for await (const entry of Deno.readDir(dir)) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory) {
      await removeGenerated(p)
      const remaining = [...Deno.readDirSync(p)].filter((e) => e.name !== ".DS_Store")
      if (remaining.length === 0) await Deno.remove(p, { recursive: true })
    } else if (entry.name.endsWith(".gen.go")) {
      await Deno.remove(p)
    }
  }
}

