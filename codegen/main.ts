function generateWebhook(): string {
  const file = new GoFile("webhook", "webhook")
  const defs = new Map<string, WebhookDefinition>()
  for (const def of webhookSchema.entities as WebhookDefinition[]) {
    defs.set(def.name, def)
  }
  const isInterface = (name: string) => {
    const d = defs.get(name)
    return d?.type === "object" && d.interface !== null
  }
  const leaves = (name: string): string[] => {
    const d = defs.get(name)
    if (!d || d.type !== "object") throw new Error(`unknown webhook type ${name}`)
    if (!d.interface) return [name]
    return d.interface.coproduct.flatMap(leaves)
  }
  // 판별자가 없는 인터페이스(데이터 그룹)는 marker interface 로 표현
  const markers = new Map<string, string[]>()
  for (const def of defs.values()) {
    if (def.type !== "object" || !def.interface || def.interface.discriminant) {
      continue
    }
    for (const leaf of leaves(def.name)) {
      markers.set(leaf, [...(markers.get(leaf) ?? []), def.name])
    }
  }
  const discriminantOf = (name: string, property: string): string => {
    const d = defs.get(name)
    if (!d || d.type !== "object") throw new Error(`unknown webhook type ${name}`)
    const p = d.properties.find((p) => p.type === "discriminant" && p.name === property)
    if (!p || p.type !== "discriminant") {
      throw new Error(`webhook ${name} has no discriminant ${property}`)
    }
    return p.value
  }
  const propType = (p: WebhookProperty): GoType => {
    switch (p.type) {
      case "string":
        return { type: "string", nilable: false }
      case "integer":
        return { type: "int64", nilable: false }
      case "ref":
        if (isInterface(p.value)) {
          const d = defs.get(p.value)!
          if (d.type === "object" && d.interface && !d.interface.discriminant) {
            throw new Error(`reference to non-discriminated webhook interface ${p.value}`)
          }
        }
        return { type: p.value, nilable: false }
      default:
        throw new Error(`unsupported webhook property ${p.type}`, { cause: p })
    }
  }
  for (const def of defs.values()) {
    if (def.type !== "object") {
      throw new Error(`unsupported webhook entity ${def.type}`, { cause: def })
    }
    if (def.interface) {
      if (def.interface.discriminant) {
        const property = def.interface.discriminant
        const variants = leaves(def.name).map((leaf) => ({
          field: leaf,
          type: leaf,
          values: [discriminantOf(leaf, property)],
          title: null,
        }))
        writeUnionType(file, def.name, def.description ?? "", property, variants)
      } else {
        file.doc("", def.name, def.description)
        file.line(`type ${def.name} interface {`)
        file.line(`\tis${def.name}()`)
        file.line("}")
        file.line()
      }
      continue
    }
    file.doc("", def.name, def.description)
    const discriminants: { name: string; value: string }[] = []
    file.line(`type ${def.name} struct {`)
    for (const p of def.properties) {
      if (p.type === "discriminant") {
        discriminants.push({ name: p.name, value: p.value })
        continue
      }
      const fieldName = pascal(p.name)
      file.doc("\t", fieldName, annotate(p.description ?? "", p))
      const t = propType(p)
      const type = !p.required && !t.nilable ? `*${t.type}` : t.type
      file.line(`\t${fieldName} ${type} ${tag(p.name, !p.required)}`)
    }
    file.line("}")
    file.line()
    if (discriminants.length > 0) {
      const alias = file.importPath(JSONUTIL_IMPORT)
      const kv = discriminants.flatMap(({ name, value }) => [goString(name), goString(value)])
        .join(", ")
      file.line(`// MarshalJSON 판별자 필드를 포함하여 직렬화합니다.`)
      file.line(`func (v ${def.name}) MarshalJSON() ([]byte, error) {`)
      file.line(`\ttype alias ${def.name}`)
      file.line(`\treturn ${alias}.MarshalWithDiscriminators(alias(v), ${kv})`)
      file.line("}")
      file.line()
    }
    for (const marker of markers.get(def.name) ?? []) {
      file.line(`func (${def.name}) is${marker}() {}`)
      file.line()
    }
  }
  return file.render()
}

