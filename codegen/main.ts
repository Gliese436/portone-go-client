/**
 * PortOne Go SDK 코드 생성기
 *
 * server-sdk 서브모듈의 공식 codegen 파서(JS/Python/Kotlin SDK가 공유하는 파서)를
 * 그대로 사용하여 openapi.json 을 해석하고, 그 결과를 Go 코드로 출력합니다.
 *
 * 실행: ./generate-sdk.sh (또는 아래 명령)
 *   deno run --no-lock --config server-sdk/codegen/deno.json \
 *     --allow-read --allow-write --allow-run codegen/main.ts
 *
 * 출력 규칙 (JS 클라이언트 동작을 기준으로 함)
 * - 엔티티는 카테고리별 패키지(portonev2/<category>)에 생성합니다.
 *   상류 파서의 배치 규칙상 의존 방향은 leaf → platform → common 으로만 흐르므로 import 순환이 없습니다.
 * - API 클라이언트는 모두 루트 패키지(portonev2)에 생성합니다.
 * - 경로/쿼리/바디 파라미터는 JS 와 동일하게 하나의 Options 구조체로 평탄화합니다.
 * - GET/DELETE 요청의 바디는 `requestBody` 쿼리 파라미터(JSON)로 전송합니다.
 * - 바디 프로퍼티가 하나도 없으면 바디를 전송하지 않습니다.
 * - storeId 는 지정하지 않으면 클라이언트에 설정된 상점 아이디를 사용합니다.
 */
