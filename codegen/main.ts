const outputs = new Map<string, string>()

function emit(relPath: string, content: string) {
  if (outputs.has(relPath)) throw new Error(`duplicated output ${relPath}`)
  outputs.set(relPath, content)
}

// 1) 카테고리별 타입 패키지
const scopes = new Map<string, Scope>()
for (const { category, pack } of packages) {
  const pkgName = categoryPkgName(category)
  const dir = categoryDir(category)
  const scope = new Scope(dir)
  scopes.set(category, scope)
  const hasOptions = pack.operations.some((op) => operationParams(op).length > 0)
  if (pack.entities.length === 0 && !hasOptions) continue

  const docFile = new GoFile(pkgName, category)
  docFile.lines.length = 0
  const docContent = [
    HEADER,
    "",
    `// Package ${pkgName} 는 포트원 API 의 ${category} 카테고리에 속한 타입을 제공합니다.`,
    `package ${pkgName}`,
    "",
  ].join("\n")
  emit(`${dir}/doc.gen.go`, docContent)

  if (pack.entities.length > 0) {
    const file = new GoFile(pkgName, category)
    const sorted = [...pack.entities].sort((a, b) => a.name.localeCompare(b.name))
    for (const entity of sorted) writeEntity(file, scope, entity)
    emit(`${dir}/types.gen.go`, file.render())
  }
  if (hasOptions) {
    const file = new GoFile(pkgName, category)
    const ops = [...pack.operations].sort((a, b) => a.id.localeCompare(b.id))
    for (const op of ops) writeOptions(file, scope, op)
    emit(`${dir}/options.gen.go`, file.render())
  }
}

