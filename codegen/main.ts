function writeEnum(file: GoFile, scope: Scope, def: Definition & { type: "enum" }) {
  file.doc("", def.name, mergeDoc(def.title, def.description))
  file.line(`type ${def.name} string`)
  file.line()
  file.line("const (")
  for (const variant of def.variants) {
    let suffix = toPascalCase(variant.value).replace(/[^A-Za-z0-9_]/g, "")
    if (!suffix || /^[0-9]/.test(suffix)) suffix = `V${suffix}`
    const constName = ident(`${def.name}${suffix}`, { def, variant })
    scope.add(constName, `${def.name}=${variant.value}`)
    const doc = mergeDoc(variant.title, variant.description)
    file.doc("\t", constName, doc || variant.value)
    file.line(`\t${constName} ${def.name} = ${goString(variant.value)}`)
  }
  file.line(")")
  file.line()
}

function writeObject(
  file: GoFile,
  def: Definition & { type: "object" },
) {
  file.doc("", def.name, mergeDoc(def.title, def.description))
  if (def.additionalProperties !== null) {
    if (def.properties.length > 0) {
      throw new Error("object with both properties and additionalProperties", {
        cause: def,
      })
    }
    const value = baseType(file, def.additionalProperties)
    file.line(`type ${def.name} map[string]${value.type}`)
    file.line()
    return
  }
  const fields = new Scope(`struct ${def.name}`)
  const discriminants: { name: string; value: string }[] = []
  file.line(`type ${def.name} struct {`)
  for (const prop of def.properties) {
    if (prop.type === "discriminant") {
      discriminants.push({ name: prop.name, value: prop.value })
      continue
    }
    const fieldName = pascal(prop.name)
    fields.add(fieldName, prop.name)
    file.doc(
      "\t",
      fieldName,
      annotate(mergeDoc(prop.title, prop.description), prop),
    )
    const t = fieldType(file, prop)
    const omit = !prop.required
    file.line(`\t${fieldName} ${t} ${tag(prop.name, omit)}`)
  }
  file.line("}")
  file.line()
  if (discriminants.length > 0) {
    const alias = file.importPath(JSONUTIL_IMPORT)
    const kv = discriminants.flatMap(({ name, value }) => [
      goString(name),
      goString(value),
    ]).join(", ")
    const desc = discriminants.map(({ name, value }) => `"${name}": "${value}"`)
      .join(", ")
    file.line(`// MarshalJSON 판별자 필드(${desc})를 포함하여 직렬화합니다.`)
    file.line(`func (v ${def.name}) MarshalJSON() ([]byte, error) {`)
    file.line(`\ttype alias ${def.name}`)
    file.line(`\treturn ${alias}.MarshalWithDiscriminators(alias(v), ${kv})`)
    file.line("}")
    file.line()
  }
}

type UnionVariant = { field: string; type: string; values: string[]; title: string | null }

function writeUnionType(
  file: GoFile,
  name: string,
  doc: string,
  property: string,
  variants: UnionVariant[],
) {
  const discField = pascal(property)
  const fields = new Scope(`union ${name}`)
  fields.add(discField, property)
  fields.add("Unrecognized", "unrecognized")
  const jsonAlias = file.importPath("encoding/json")
  const jsonutil = file.importPath(JSONUTIL_IMPORT)
  file.doc("", name, doc)
  file.line("//")
  file.line(
    `// 판별자 "${property}" 값에 따라 아래 variant 필드 중 하나가 채워집니다.`,
  )
  file.line(
    "// 알 수 없는 값이면 Unrecognized 에 원본 JSON 이 보관됩니다.",
  )
  file.line(`type ${name} struct {`)
  file.line(`\t// ${discField} 판별자("${property}") 값`)
  file.line(`\t${discField} string ${"`json:\"-\"`"}`)
  for (const v of variants) {
    fields.add(v.field, v.type)
    const label = v.title ? `${v.title} (${v.values.join(", ")})` : v.values.join(", ")
    file.line(`\t// ${v.field} ${label}`)
    file.line(`\t${v.field} *${v.type} ${"`json:\"-\"`"}`)
  }
  file.line("\t// Unrecognized 알 수 없는 variant 의 원본 JSON")
  file.line(`\tUnrecognized ${jsonAlias}.RawMessage ${"`json:\"-\"`"}`)
  file.line("}")
  file.line()
  file.line(`// UnmarshalJSON 판별자 값에 맞는 variant 로 역직렬화합니다.`)
  file.line(`func (u *${name}) UnmarshalJSON(data []byte) error {`)
  file.line(`\tif ${jsonutil}.IsNull(data) {`)
  file.line(`\t\t*u = ${name}{}`)
  file.line("\t\treturn nil")
  file.line("\t}")
  file.line("\tvar probe struct {")
  file.line(`\t\tValue string ${tag(property, false)}`)
  file.line("\t}")
  file.line(`\tif err := ${jsonAlias}.Unmarshal(data, &probe); err != nil {`)
  file.line("\t\treturn err")
  file.line("\t}")
  file.line(`\t*u = ${name}{${discField}: probe.Value}`)
  file.line("\tswitch probe.Value {")
  for (const v of variants) {
    file.line(`\tcase ${v.values.map(goString).join(", ")}:`)
    file.line(`\t\tu.${v.field} = new(${v.type})`)
    file.line(`\t\treturn ${jsonAlias}.Unmarshal(data, u.${v.field})`)
  }
  file.line("\t}")
  file.line(`\tu.Unrecognized = append(${jsonAlias}.RawMessage(nil), data...)`)
  file.line("\treturn nil")
  file.line("}")
  file.line()
  file.line(`// MarshalJSON 채워진 variant 를 판별자 필드와 함께 직렬화합니다.`)
  file.line(`func (u ${name}) MarshalJSON() ([]byte, error) {`)
  file.line("\tswitch {")
  for (const v of variants) {
    file.line(`\tcase u.${v.field} != nil:`)
    file.line(`\t\treturn ${jsonAlias}.Marshal(u.${v.field})`)
  }
  file.line("\tcase u.Unrecognized != nil:")
  file.line("\t\treturn u.Unrecognized, nil")
  file.line("\t}")
  file.line(`\treturn []byte("null"), nil`)
  file.line("}")
  file.line()
  file.line(
    "// Value 채워진 variant 의 포인터를 반환합니다. type switch 에 사용할 수 있으며, 알 수 없는 variant 이면 nil 입니다.",
  )
  file.line(`func (u ${name}) Value() any {`)
  file.line("\tswitch {")
  for (const v of variants) {
    file.line(`\tcase u.${v.field} != nil:`)
    file.line(`\t\treturn u.${v.field}`)
  }
  file.line("\t}")
  file.line("\treturn nil")
  file.line("}")
  file.line()
}

function writeOneOf(file: GoFile, def: Definition & { type: "oneOf" }) {
  const grouped = new Map<string, UnionVariant>()
  for (const variant of def.variants) {
    const existing = grouped.get(variant.name)
    if (existing) {
      existing.values.push(variant.value)
      continue
    }
    grouped.set(variant.name, {
      field: ident(variant.name, variant),
      type: qualify(file, variant.name),
      values: [variant.value],
      title: variant.title,
    })
  }
  writeUnionType(
    file,
    def.name,
    mergeDoc(def.title, def.description),
    def.property,
    [...grouped.values()],
  )
}

function writeEntity(file: GoFile, scope: Scope, def: Definition) {
  scope.add(def.name, "entity")
  switch (def.type) {
    case "enum":
      writeEnum(file, scope, def)
      break
    case "object":
      writeObject(file, def)
      break
    case "oneOf":
      writeOneOf(file, def)
      break
    case "string":
    case "boolean":
    case "integer":
    case "number": {
      file.doc("", def.name, mergeDoc(def.title, def.description))
      file.line(`type ${def.name} ${baseType(file, def).type}`)
      file.line()
      break
    }
    default:
      throw new Error(`unsupported entity type ${def.type}`, { cause: def })
  }
}

