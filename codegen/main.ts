type Param = Property & { location: "path" | "query" | "body" }

function operationParams(op: Operation): Param[] {
  return [
    ...op.params.path.map((p) => ({ ...p, location: "path" as const })),
    ...op.params.query.map((p) => ({ ...p, location: "query" as const })),
    ...fetchBodyProperties(op).map((p) => ({ ...p, location: "body" as const })),
  ]
}

function optionsTypeName(op: Operation): string {
  return `${pascal(op.id)}Options`
}

function writeOptions(file: GoFile, scope: Scope, op: Operation) {
  const params = operationParams(op)
  if (params.length === 0) return
  const name = optionsTypeName(op)
  scope.add(name, `options of ${op.id}`)
  const fields = new Scope(`options ${name}`)
  file.line(`// ${name} ${pascal(op.id)} 요청 파라미터`)
  file.line("//")
  file.line(`// ${op.method.toUpperCase()} ${op.path}`)
  file.line(`type ${name} struct {`)
  for (const param of params) {
    if (param.type === "discriminant") {
      throw new Error("discriminant parameter is not supported", { cause: op })
    }
    const fieldName = pascal(param.name)
    fields.add(fieldName, `${param.location}:${param.name}`)
    let doc = annotate(mergeDoc(param.title, param.description), param)
    if (param.name === "storeId") {
      doc = [doc, "지정하지 않으면 클라이언트에 설정된 상점 아이디를 사용합니다."]
        .filter(Boolean).join("\n\n")
    }
    file.doc("\t", fieldName, doc)
    const t = param.location === "path"
      ? baseType(file, param).type
      : fieldType(file, param)
    file.line(`\t${fieldName} ${t}`)
  }
  file.line("}")
  file.line()
}

/** 쿼리/경로 값을 문자열로 변환하는 Go 식 */
function stringExpr(file: GoFile, def: Definition, expr: string): string {
  switch (def.type) {
    case "string":
      return expr
    case "boolean":
      return `${file.importPath("strconv")}.FormatBool(${expr})`
    case "integer":
      return `${file.importPath("strconv")}.FormatInt(${expr}, 10)`
    case "number":
      return `${file.importPath("strconv")}.FormatFloat(${expr}, 'f', -1, 64)`
    case "ref": {
      const target = entityMap.get(def.value)
      if (target?.type !== "enum" && target?.type !== "string") {
        throw new Error("non-scalar query/path parameter", { cause: def })
      }
      return `string(${expr})`
    }
    default:
      throw new Error(`unsupported query/path parameter ${def.type}`, {
        cause: def,
      })
  }
}

function writeMethod(
  file: GoFile,
  clientType: string,
  op: Operation,
) {
  const category = normalizeCategory(op.category)
  const params = operationParams(op)
  const bodyProps = params.filter((p) => p.location === "body")
  const queryParams = params.filter((p) => p.location === "query")
  const method = op.method.toLowerCase()
  const bodyInQuery = method === "get" || method === "delete"
  const hasBody = bodyProps.length > 0
  const usesQuery = queryParams.length > 0 || (hasBody && bodyInQuery)
  const methodName = pascal(op.id)
  const httpAlias = file.importPath("net/http")
  const httpMethod = `${httpAlias}.Method${pascal(method)}`

  let returnType: string
  let zero: string
  switch (op.response?.type) {
    case "application/json":
      returnType = `*${qualify(file, op.response.schema)}`
      zero = "nil"
      break
    case "text/csv":
      returnType = "string"
      zero = `""`
      break
    case undefined:
      returnType = ""
      zero = ""
      break
    default:
      throw new Error("unknown response type", { cause: op })
  }

  // 문서 주석
  const description = (op.description ?? "").trim()
  const [summary, ...rest] = description ? description.split("\n") : [methodName]
  file.line(`// ${methodName} ${summary.trim()}`.trimEnd())
  const restText = rest.join("\n").trim()
  if (restText) {
    file.line("//")
    for (const l of restText.split("\n")) {
      file.line(l.trim() ? `// ${l.trimEnd()}` : "//")
    }
  }
  file.line("//")
  file.line(`// ${op.method.toUpperCase()} ${op.path}`)
  file.line("//")
  file.line(
    `// 실패 시 *APIError 를 반환하며, APIError.Decode 로 ${categoryPkgName(categoryMap.get(op.errors) ?? category)}.${op.errors} 에 디코딩할 수 있습니다.`,
  )
  if (op.unstable) {
    file.line("//")
    file.line(`// Unstable: ${UNSTABLE_DESCRIPTION}`)
  }

  const optionsType = params.length > 0
    ? `*${file.importPath(categoryImport(category), categoryPkgName(category))}.${optionsTypeName(op)}`
    : null
  const optionsArg = optionsType ? `, opts ${optionsType}` : ""
  const ret = returnType ? `(${returnType}, error)` : "error"
  file.line(
    `func (c *${clientType}) ${methodName}(ctx ${file.importPath("context")}.Context${optionsArg}) ${ret} {`,
  )
  const fail = (err: string) =>
    returnType ? `return ${zero}, ${err}` : `return ${err}`
  if (optionsType) {
    file.line("\tif opts == nil {")
    file.line(`\t\topts = &${optionsType.slice(1)}{}`)
    file.line("\t}")
  }

  // 쿼리
  if (usesQuery) {
    file.line(`\tquery := ${file.importPath("net/url")}.Values{}`)
  }
  for (const q of queryParams) {
    const field = `opts.${pascal(q.name)}`
    if (q.name === "storeId") {
      if (q.required) {
        file.line(`\tquery.Set("storeId", c.client.storeIDValue(${field}))`)
      } else {
        file.line(`\tif v := c.client.storeIDPtr(${field}); v != nil {`)
        file.line(`\t\tquery.Set("storeId", *v)`)
        file.line("\t}")
      }
      continue
    }
    const base = baseType(file, q)
    if (q.required || base.nilable) {
      if (q.type === "array") {
        throw new Error("array query parameter is not supported", { cause: op })
      }
      file.line(`\tquery.Set(${goString(q.name)}, ${stringExpr(file, q, field)})`)
    } else {
      file.line(`\tif ${field} != nil {`)
      file.line(
        `\t\tquery.Set(${goString(q.name)}, ${stringExpr(file, q, `*${field}`)})`,
      )
      file.line("\t}")
    }
  }

  // 바디
  if (hasBody) {
    const bodyName = op.params.body!.type === "ref"
      ? qualify(file, op.params.body!.value)
      : (() => {
        throw new Error("unsupported body", { cause: op })
      })()
    file.line(`\tbody := ${bodyName}{`)
    for (const p of bodyProps) {
      const field = pascal(p.name)
      if (p.name === "storeId") {
        file.line(
          p.required
            ? `\t\t${field}: c.client.storeIDValue(opts.${field}),`
            : `\t\t${field}: c.client.storeIDPtr(opts.${field}),`,
        )
      } else {
        file.line(`\t\t${field}: opts.${field},`)
      }
    }
    file.line("\t}")
    if (bodyInQuery) {
      file.line(`\tif err := setRequestBodyQuery(query, body); err != nil {`)
      file.line(`\t\t${fail("err")}`)
      file.line("\t}")
    }
  }

  // 경로
  const segments: string[] = []
  let last = 0
  for (const match of op.path.matchAll(/\{([^}]+)\}/g)) {
    const literal = op.path.slice(last, match.index)
    if (literal) segments.push(goString(literal))
    const param = op.params.path.find((p) => p.name === match[1])
    if (!param) throw new Error(`missing path param ${match[1]}`, { cause: op })
    segments.push(
      `${file.importPath("net/url")}.PathEscape(${stringExpr(file, param, `opts.${pascal(param.name)}`)})`,
    )
    last = match.index! + match[0].length
  }
  const tail = op.path.slice(last)
  if (tail) segments.push(goString(tail))
  const pathExpr = segments.join(" + ")

  const queryArg = usesQuery ? "query" : "nil"
  const bodyArg = hasBody && !bodyInQuery ? "body" : "nil"
  switch (op.response?.type) {
    case "application/json":
      file.line(`\tvar result ${returnType.slice(1)}`)
      file.line(
        `\tif err := c.client.do(ctx, ${httpMethod}, ${pathExpr}, ${queryArg}, ${bodyArg}, &result); err != nil {`,
      )
      file.line(`\t\t${fail("err")}`)
      file.line("\t}")
      file.line("\treturn &result, nil")
      break
    case "text/csv":
      file.line(
        `\treturn c.client.doText(ctx, ${httpMethod}, ${pathExpr}, ${queryArg}, ${bodyArg})`,
      )
      break
    default:
      file.line(
        `\treturn c.client.do(ctx, ${httpMethod}, ${pathExpr}, ${queryArg}, ${bodyArg}, nil)`,
      )
  }
  file.line("}")
  file.line()
}

